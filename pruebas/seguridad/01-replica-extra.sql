-- Funciones, copiadas de producción --------------------------------------
create or replace function public.texto_sin_montos(t text) returns text
language sql immutable set search_path to 'public', 'pg_temp' as $$
  select btrim(regexp_replace(regexp_replace(
    coalesce(t, ''), '\(?\$\s?[0-9][0-9,\.]*\)?', '$•••', 'g'), '\s{2,}', ' ', 'g'));
$$;

create or replace function public.dia_es(f date) returns text
language sql immutable as $$
  select extract(day from f)::text || ' de ' ||
         (array['enero','febrero','marzo','abril','mayo','junio','julio','agosto',
                'septiembre','octubre','noviembre','diciembre'])[extract(month from f)::int] ||
         ' de ' || extract(year from f)::text;
$$;

