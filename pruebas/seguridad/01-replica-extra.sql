create or replace function public.fn_diario_punto() returns trigger
language plpgsql security definer as $$
begin
  if new.hecho and not old.hecho and new.proyecto_id is not null then
    insert into diario (proyecto_id, texto) values (new.proyecto_id, '✓ ' || coalesce(new.texto_en, new.texto));
  end if;
  return new;
end $$;
-- fn_factura_cobrada: en producción tampoco tiene search_path
create or replace function public.fn_factura_cobrada() returns trigger language plpgsql as $$
begin
  if new.pagada = true and (old.pagada is distinct from true) and coalesce(new.cobrado, 0) < new.monto then
    new.cobrado := new.monto;
  end if;
  if new.cobrado is null then new.cobrado := case when new.pagada then new.monto else 0 end; end if;
  return new;
end $$;
alter function public.fn_factura_cobrada() reset search_path;

