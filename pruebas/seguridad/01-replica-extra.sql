create or replace view public.proyectos_equipo as
  select id, nombre, direccion, cliente, via, tipo, work_subtype, estado, fase, origen,
         horas_estimadas, horas_reales_base, actualizado, portal_completo, portal_dinero,
         texto_sin_montos(estado_detalle) as estado_detalle,
         texto_sin_montos(proxima_accion) as proxima_accion,
         texto_sin_montos(ref) as ref
    from proyectos where es_activo();
create or replace view public.materiales_equipo as
  select id, proyecto_id, descripcion, cantidad, estado, origen_pendiente, autor_id, creado
    from materiales where es_activo();
create or replace view public.alcances_equipo as
  select id, proyecto_id, tipo, titulo, ref, estado, orden from alcances where es_activo();
create or replace view public.documentos_equipo as
  select id, proyecto_id, titulo, clase from documentos where es_activo();
-- recibos_equipo ya la crea el banco; se rehace igual que en producción.
create or replace view public.recibos_equipo as
  select id, proyecto_id, ruta, estado, autor_id, creado from recibos where es_activo();
drop view if exists public.asistente_costo_mes;
create view public.asistente_costo_mes with (security_invoker = true) as
  select to_char((creado at time zone 'America/New_York'), 'YYYY-MM') as mes,
         coalesce(accion, 'asistente') as accion, count(*) as llamadas,
         coalesce(sum(costo_centavos), 0) as centavos
    from asistente_uso group by 1, 2;

