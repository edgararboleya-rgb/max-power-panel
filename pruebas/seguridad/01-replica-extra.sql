create or replace function public.fn_mandar_urgente(txt text, pid text) returns void
language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
declare
  nom text;
  limpio text;
begin
  select nombre into nom from proyectos where id = pid;
  limpio := regexp_replace(coalesce(txt, ''), '\$\s?[0-9][0-9,.]*', '$•••', 'g');
  perform fn_cartero(jsonb_build_object(
    'titulo', '🔴 URGENTE',
    'cuerpo', limpio || ' — ' || coalesce(nom, 'General')));
end $$;

create or replace function public.fn_urgente_pendiente() returns trigger
language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
begin
  if new.prioridad = 'urgente'
     and (tg_op = 'INSERT' or old.prioridad is distinct from 'urgente')
     and not coalesce(new.resuelto, false) then
    perform fn_mandar_urgente(new.descripcion, new.proyecto_id);
  end if;
  return new;
end $$;

create or replace function public.fn_avisar_horas() returns trigger
language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
begin
  if exists (select 1 from perfiles where id = new.usuario_id and rol <> 'dueno') then
    perform fn_cartero(jsonb_build_object('table', 'horas', 'record', to_jsonb(new)));
  end if;
  return new;
end $$;

create or replace function public.fn_nto_recordatorio(p_proyecto text) returns void
language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
declare
  v_modo   text;
  v_nombre text;
  v_ya     timestamptz;
  v_horas  date;
  v_recibo date;
  v_primer date;
  v_limite date;
  v_hoy    date := (now() at time zone 'America/New_York')::date;
  v_texto  text;
  v_abierto record;
begin
  select p.contratista_modo, p.nombre, p.nto_enviado_el
    into v_modo, v_nombre, v_ya
    from proyectos p where p.id = p_proyecto;
  if v_modo is distinct from 'contrato' or v_ya is not null then return; end if;
  select min(h.fecha) into v_horas  from horas h   where h.proyecto_id = p_proyecto;
  select min(r.fecha) into v_recibo from recibos r where r.proyecto_id = p_proyecto
                                                    and coalesce(r.estado,'') <> 'anulado';
  v_primer := least(coalesce(v_horas, v_recibo, v_hoy), coalesce(v_recibo, v_horas, v_hoy));
  v_limite := v_primer + 40;
  if v_primer + 45 < v_hoy then
    v_texto := 'OJO — el plazo del Notice to Owner de ' || coalesce(v_nombre, p_proyecto) ||
               ' YA SE PASÓ: el primer día de trabajo fue el ' || dia_es(v_primer) ||
               ' y los 45 días vencieron el ' || dia_es(v_primer + 45) ||
               '. Consúltalo antes de mandarlo. Cuando lo mandes, márcalo en la obra.';
    v_limite := v_hoy;
  else
    v_texto := 'Mandar el Notice to Owner de ' || coalesce(v_nombre, p_proyecto) ||
               ' al dueño de la propiedad y al contratista antes del ' || dia_es(v_limite) ||
               '. Te lo pongo cinco días antes a propósito: el plazo de ley se cumple el ' ||
               dia_es(v_primer + 45) || ', 45 días desde el primer día de trabajo (' ||
               dia_es(v_primer) || '). Sin esto se pierde el derecho a gravamen. ' ||
               'Cuando lo mandes, márcalo en la obra y anota cómo.';
    if v_limite < v_hoy then v_limite := v_hoy; end if;
  end if;
  select * into v_abierto from pendientes
   where proyecto_id = p_proyecto
     and (descripcion like 'Mandar el Notice to Owner%' or descripcion like 'OJO — el plazo del Notice to Owner%')
   order by coalesce(resuelto, false), id desc
   limit 1;
  if found then
    if not coalesce(v_abierto.resuelto, false) and v_abierto.fecha > v_limite then
      update pendientes set fecha = v_limite, descripcion = v_texto where id = v_abierto.id;
    end if;
    return;
  end if;
  insert into pendientes (proyecto_id, descripcion, fecha, prioridad, resuelto, autor_id)
  values (p_proyecto, v_texto, v_limite, 'urgente', false,
          coalesce(auth.uid(), '00000000-0000-4000-a000-000000000001'::uuid));
end $$;

create or replace function public.fn_nto_al_apuntar_horas() returns trigger
language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
begin
  if exists (select 1 from proyectos p
              where p.id = new.proyecto_id and p.contratista_modo = 'contrato'
                and p.nto_enviado_el is null) then
    perform fn_nto_recordatorio(new.proyecto_id);
  end if;
  return new;
end $$;

create or replace function public.fn_nto_al_arrancar() returns trigger
language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
begin
  if new.contratista_modo = 'contrato' and new.estado = 'ejecucion' then
    if tg_op = 'INSERT' then
      perform fn_nto_recordatorio(new.id);
    elsif old.estado is distinct from new.estado
       or old.contratista_modo is distinct from new.contratista_modo then
      perform fn_nto_recordatorio(new.id);
    end if;
  end if;
  return new;
end $$;

create or replace function public.fn_nto_al_resolver() returns trigger
language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
begin
  if coalesce(new.resuelto, false) and not coalesce(old.resuelto, false)
     and new.proyecto_id is not null
     and (new.descripcion like 'Mandar el Notice to Owner%'
       or new.descripcion like 'OJO — el plazo del Notice to Owner%') then
    update proyectos set nto_enviado_el = coalesce(nto_enviado_el, now())
     where id = new.proyecto_id;
  end if;
  return new;
end $$;

create or replace function public.fn_llave_contratista_nueva() returns trigger
language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
begin
  insert into contratista_llaves (contratista_id, token)
  values (new.id, replace(gen_random_uuid()::text, '-', ''))
  on conflict (contratista_id) do nothing;
  return new;
end $$;

create or replace function public.fn_estuve() returns void
language sql security definer set search_path to 'public' as $$
  update perfiles set ultima_vista = now() where id = auth.uid();
$$;

