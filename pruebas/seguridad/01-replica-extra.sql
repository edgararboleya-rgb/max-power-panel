-- Funciones: tres grupos, tal cual los devuelve pg_proc.proacl.
do $$
declare f text;
begin
  -- Con PUBLIC (=X/postgres): las ocho que el asesor marca.
  foreach f in array array['public.fn_llave_contratista_nueva()', 'public.fn_nto_al_apuntar_horas()',
      'public.fn_nto_al_arrancar()', 'public.fn_nto_al_resolver()', 'public.fn_nto_recordatorio(text)',
      'public.dia_es(date)', 'public.fn_factura_cobrada()', 'public.fn_lev_tocado()'] loop
    execute format('revoke all on function %s from public, anon, authenticated, service_role', f);
    execute format('grant execute on function %s to public, authenticated, service_role', f);
  end loop;
  -- authenticated + service_role.
  foreach f in array array['public.es_dueno()', 'public.es_activo()', 'public.fn_avisar_horas()',
      'public.fn_avisa_correccion()', 'public.fn_urgente_pendiente()', 'public.fn_estuve()',
      'public.fn_diario_punto()', 'public.planos_touch()', 'public.texto_sin_montos(text)',
      'public.fn_guarda_correccion()', 'public.fn_recibo_marca_material()'] loop
    if to_regprocedure(f) is not null then
      execute format('revoke all on function %s from public, anon, authenticated, service_role', f);
      execute format('grant execute on function %s to authenticated, service_role', f);
    end if;
  end loop;
  -- Solo el servidor.
  foreach f in array array['public.fn_cartero(jsonb)', 'public.fn_mandar_urgente(text,text)'] loop
    execute format('revoke all on function %s from public, anon, authenticated, service_role', f);
    execute format('grant execute on function %s to service_role', f);
  end loop;
end $$;
