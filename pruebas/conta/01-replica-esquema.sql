-- =====================================================================
-- Funciones de permiso: copiadas verbatim de producción. Se reutilizan
-- en todo el libro; no se inventa otro candado.
-- =====================================================================
create or replace function public.es_dueno() returns boolean
language sql stable security definer set search_path to 'public','pg_temp' as $$
  select exists (select 1 from perfiles
    where id = auth.uid() and rol = 'dueno' and coalesce(activo, true));
$$;

create or replace function public.es_activo() returns boolean
language sql stable security definer set search_path to 'public','pg_temp' as $$
  select coalesce((select coalesce(activo, true) from perfiles where id = auth.uid()), false);
$$;

