-- facturas: BEFORE INSERT OR UPDATE → trg_factura_cobrada (verbatim; en
-- producción NO tiene search_path fijo y aquí tampoco).
create or replace function public.fn_factura_cobrada() returns trigger language plpgsql as $$
begin
  if new.pagada = true and (old.pagada is distinct from true) and coalesce(new.cobrado, 0) < new.monto then
    new.cobrado := new.monto;
  end if;
  if new.cobrado is null then new.cobrado := case when new.pagada then new.monto else 0 end; end if;
  return new;
end $$;

drop trigger if exists trg_factura_cobrada on public.facturas;
create trigger trg_factura_cobrada before insert or update on public.facturas
  for each row execute function public.fn_factura_cobrada();

-- recibos: AFTER INSERT OR UPDATE → trg_recibo_marca_material (verbatim).
create or replace function public.fn_recibo_marca_material() returns trigger
language plpgsql security definer set search_path to 'public','pg_temp' as $$
begin
  if new.proyecto_id is not null and new.notas is not null
     and coalesce(new.estado, '') <> 'anulado' then
    update materiales m
      set estado = 'comprado', recibo_id = new.id
      where m.proyecto_id = new.proyecto_id
        and m.estado = 'falta'
        and length(trim(m.descripcion)) >= 6
        and strpos(lower(new.notas), lower(trim(m.descripcion))) > 0;
  end if;
  if tg_op = 'UPDATE' and new.estado = 'anulado' and coalesce(old.estado, '') <> 'anulado' then
    update materiales set estado = 'falta', recibo_id = null where recibo_id = new.id;
  end if;
  return new;
end $$;

drop trigger if exists trg_recibo_marca_material on public.recibos;
create trigger trg_recibo_marca_material after insert or update on public.recibos
  for each row execute function public.fn_recibo_marca_material();

-- horas: BEFORE UPDATE → trg_guarda_correccion (verbatim). El dueño edita
-- libre; el equipo solo con permiso de un uso.
create or replace function public.fn_guarda_correccion() returns trigger
language plpgsql security definer set search_path to 'public','pg_temp' as $$
begin
  if exists (select 1 from perfiles where id = auth.uid() and rol = 'dueno') then
    return new;  -- el dueño edita libre
  end if;
  if old.correccion_estado = 'aprobada' then
    new.correccion_estado := null;  -- permiso de un solo uso
    return new;
  end if;
  if coalesce(new.correccion_estado, '') = 'pedida'
     and new.horas = old.horas and new.fecha = old.fecha
     and coalesce(new.notas, '') = coalesce(old.notas, '')
     and coalesce(new.fase, '') = coalesce(old.fase, '')
     and coalesce(new.proyecto_id, '') = coalesce(old.proyecto_id, '') then
    return new;
  end if;
  raise exception 'Pídele permiso a Edgar para corregir este reporte (toca ✎ y confirma)';
end $$;

drop trigger if exists trg_guarda_correccion on public.horas;
create trigger trg_guarda_correccion before update on public.horas
  for each row execute function public.fn_guarda_correccion();

