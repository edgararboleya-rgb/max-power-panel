    from recibos
   where es_activo();

-- asistente_costo_mes: en producción es una vista sobre asistente_uso; su
-- texto no se leyó. Esta es una aproximación con las columnas que lee la
-- app (mes, accion, llamadas, centavos), mes de Florida.
create or replace view public.asistente_costo_mes with (security_invoker = true) as
  select to_char((creado at time zone 'America/New_York'), 'YYYY-MM') as mes,
         accion,
         count(*)::int                       as llamadas,
         coalesce(sum(costo_centavos), 0)::int as centavos
    from asistente_uso
   group by 1, 2;
