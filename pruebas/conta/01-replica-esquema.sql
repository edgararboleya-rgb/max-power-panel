-- Avisos de horas (AFTER): en producción arman un mensaje y llaman a
-- fn_cartero. Sus cuerpos no se leyeron; aquí llaman al stub con lo mínimo
-- para que el camino (trigger → fn_cartero → net) exista y no falle.
create or replace function public.fn_avisar_horas() returns trigger
language plpgsql security definer set search_path to 'public','pg_temp' as $$
begin
  perform fn_cartero(jsonb_build_object('tipo', 'horas', 'id', new.id));
  return new;
end $$;

